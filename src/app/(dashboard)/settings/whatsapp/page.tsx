import type { Metadata } from "next";
import { Suspense } from "react";
import { Bot, CheckCircle2, Download, MessageCircle, Printer, XCircle } from "lucide-react";
import { Alert } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { buttonVariants } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { EmptyState } from "@/components/ui/empty-state";
import { SkeletonList } from "@/components/ui/skeleton";
import { can } from "@/lib/auth/permissions";
import { requirePermission } from "@/lib/auth/session";
import { getBotOverview } from "@/lib/bot/settings";
import { formatDateTime } from "@/lib/time";
import { ORDER_GREETING_TEXT, qrSvg, waMeLink } from "@/lib/whatsapp/links";
import { getStatusMessageSettings, getWhatsAppNumber } from "@/lib/whatsapp/queries";
import { BotSettingsForm } from "./bot-settings-form";
import { StatusMessagesForm } from "./status-messages-form";

export const metadata: Metadata = { title: "WhatsApp" };

/** Owners/managers: connection status, QR code, order status messages. Only the platform admin connects numbers. */
async function WhatsAppSettings() {
  const ctx = await requirePermission("settings.view", { onDenied: "redirect" });
  // User client: RLS + column grants (the token column is never readable).
  const [account, statusMessages] = await Promise.all([
    getWhatsAppNumber(ctx.restaurant.id),
    getStatusMessageSettings(ctx.restaurant.id),
  ]);
  const bot = await getBotOverview(ctx.restaurant.id, ctx.restaurant.timezone);

  if (!account) {
    return (
      <EmptyState
        tone="brand"
        icon={<MessageCircle />}
        title="WhatsApp is not connected yet"
        description="Contact Orderly support to connect your WhatsApp Business number. Customers can then message you to order."
      />
    );
  }

  const branch = ctx.branches.find((b) => b.id === account.branch_id);
  const link = waMeLink(account.display_phone_number);
  // Generated by the qrcode library from a digits-only wa.me link: safe markup.
  const svg = link ? await qrSvg(link) : null;

  return (
    <div className="flex max-w-2xl flex-col gap-4">
      <Card padding="lg" className="flex flex-col gap-4">
        <div className="flex items-center gap-3">
          <MessageCircle aria-hidden className="size-6 text-whatsapp" />
          <p className="flex-1 text-lg font-bold">{account.display_phone_number}</p>
          {account.is_active ? (
            <Badge tone="ready" icon={<CheckCircle2 />}>Connected</Badge>
          ) : (
            <Badge tone="cancelled" icon={<XCircle />}>Off</Badge>
          )}
        </div>
        <dl className="grid grid-cols-[auto_1fr] gap-x-4 gap-y-2 text-sm">
          <dt className="text-muted">WhatsApp orders go to</dt>
          <dd className="font-semibold">{branch?.name ?? "Your first branch"}</dd>
          <dt className="text-muted">Connected on</dt>
          <dd>{formatDateTime(account.connected_at, ctx.restaurant.timezone)}</dd>
        </dl>
      </Card>

      {link && svg ? (
        <Card padding="lg" className="flex flex-col gap-4" aria-labelledby="qr-title">
          <div>
            <h2 id="qr-title" className="text-lg font-bold">QR code for customers</h2>
            <p className="text-sm text-muted">
              Customers scan it and WhatsApp opens with “{ORDER_GREETING_TEXT}” ready to send. Put it on your counter, tables
              and delivery bags.
            </p>
          </div>
          <div className="flex flex-col items-center gap-4 sm:flex-row sm:items-start">
            <div
              className="size-48 shrink-0 rounded-control border border-line bg-white p-1"
              role="img"
              aria-label={`QR code that opens WhatsApp chat with ${account.display_phone_number}`}
              dangerouslySetInnerHTML={{ __html: svg }}
            />
            <div className="flex w-full min-w-0 flex-col gap-3">
              <p className="text-sm">
                <span className="text-muted">Link: </span>
                <a href={link} target="_blank" rel="noopener noreferrer" className="break-all font-semibold text-brand-700 underline">
                  {link.replace("https://", "").split("?")[0]}
                </a>
              </p>
              <a href="/api/whatsapp/qr" download className={buttonVariants({ variant: "secondary", fullWidth: true })}>
                <Download aria-hidden /> Download QR (PNG)
              </a>
              <a href="/print/whatsapp-poster" target="_blank" rel="noopener" className={buttonVariants({ fullWidth: true })}>
                <Printer aria-hidden /> Print A5 poster
              </a>
            </div>
          </div>
        </Card>
      ) : null}

      <Card padding="lg" className="flex flex-col gap-4" aria-labelledby="bot-title">
        <div>
          <h2 id="bot-title" className="flex items-center gap-2 text-lg font-bold">
            <Bot aria-hidden className="size-5" /> AI order bot
          </h2>
          <p className="text-sm text-muted">
            Answers customers in Roman Urdu, English and Urdu, takes the order and sends it to you to accept. When it can&apos;t
            help, it hands the chat to your staff (you&apos;ll see “Needs staff” in Inbox).
          </p>
        </div>
        {bot.overBudget ? (
          <Alert title="AI budget used up for this month">
            New WhatsApp chats go straight to your staff until next month. Contact Orderly support to raise the limit.
          </Alert>
        ) : null}
        <dl className="grid grid-cols-2 gap-3">
          <div className="rounded-control bg-subtle p-3">
            <dt className="text-sm text-muted">Bot chats today</dt>
            <dd className="text-2xl font-bold">{bot.conversationsToday}</dd>
          </div>
          <div className="rounded-control bg-subtle p-3">
            <dt className="text-sm text-muted">Orders by the bot today</dt>
            <dd className="text-2xl font-bold">{bot.botOrdersToday}</dd>
          </div>
        </dl>
        <BotSettingsForm
          initial={{ botEnabled: bot.botEnabled, highValueCodThreshold: bot.highValueCodThreshold }}
          canEdit={can(ctx.role, "settings.edit")}
        />
      </Card>

      <Card padding="lg" className="flex flex-col gap-3" aria-labelledby="status-title">
        <div>
          <h2 id="status-title" className="text-lg font-bold">Order updates to customers</h2>
          <p className="text-sm text-muted">
            When you change an order&apos;s status, the customer gets a short WhatsApp message. Choose which ones to send.
          </p>
        </div>
        <Alert tone="info">
          WhatsApp only lets us message customers who wrote to you in the last 24 hours. Others don&apos;t get the update
          (you can see it as “Not sent” in Inbox).
        </Alert>
        <StatusMessagesForm initial={statusMessages} canEdit={can(ctx.role, "settings.edit")} />
      </Card>

    </div>
  );
}

export default function WhatsAppSettingsPage() {
  return (
    <Suspense fallback={<SkeletonList count={3} />}>
      <WhatsAppSettings />
    </Suspense>
  );
}
