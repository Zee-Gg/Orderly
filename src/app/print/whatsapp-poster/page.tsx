import { Suspense } from "react";
import { redirect } from "next/navigation";
import { PrintControls } from "@/components/print/print-controls";
import { requirePermission } from "@/lib/auth/session";
import { menuPageUrlForRequest } from "@/lib/menu-page/server-links";
import { qrSvg, waMeLink } from "@/lib/whatsapp/links";
import { getWhatsAppNumber } from "@/lib/whatsapp/queries";

type Search = { preview?: string; qr?: string };

/**
 * A5 poster for the counter / tables: logo, name, QR. Default QR opens the
 * WhatsApp chat; ?qr=menu opens the customer menu page (Phase 8).
 */
async function Poster({ searchParams }: { searchParams: Promise<Search> }) {
  const ctx = await requirePermission("settings.view", { onDenied: "redirect" });
  const [sp, account] = await Promise.all([searchParams, getWhatsAppNumber(ctx.restaurant.id)]);
  const menu = sp.qr === "menu";
  const chatLink = account ? waMeLink(account.display_phone_number) : null;
  if (!account || !chatLink) redirect("/settings/whatsapp");
  const link = menu ? await menuPageUrlForRequest(ctx.restaurant.slug) : chatLink;
  // Generated by the qrcode library from our own wa.me / menu URL: safe markup.
  const svg = await qrSvg(link);

  return (
    <>
      <title>{`WhatsApp poster · ${ctx.restaurant.name}`}</title>
      <style>{`
        @page { size: A5 portrait; margin: 0; }
        html, body { margin: 0; background: #fff; }
        .poster {
          width: 148mm; height: 210mm; box-sizing: border-box; margin: 0 auto; padding: 12mm 12mm 10mm;
          display: flex; flex-direction: column; align-items: center; text-align: center; gap: 4mm;
          font-family: system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; color: #000;
          -webkit-print-color-adjust: exact; print-color-adjust: exact;
        }
        .poster .logo { height: 22mm; max-width: 60mm; object-fit: contain; }
        .poster h1 { font-size: 26pt; line-height: 1.1; margin: 0; font-weight: 800; }
        .poster .cta { background: #25d366; color: #fff; border-radius: 4mm; padding: 3mm 6mm; font-size: 18pt; font-weight: 800; }
        .poster .urdu { font-size: 13pt; margin: 0; }
        .poster .qr { width: 95mm; height: 95mm; }
        .poster .qr svg { width: 100%; height: 100%; display: block; }
        .poster .number { font-size: 16pt; font-weight: 700; margin: 0; letter-spacing: 0.5pt; }
        .poster .help { font-size: 10pt; color: #333; margin: auto 0 0; }
        @media screen { body { background: #e7e5e4; } .poster { background: #fff; margin: 16px auto; box-shadow: 0 2px 12px rgb(0 0 0 / 0.15); } }
        @media print { .no-print { display: none !important; } }
      `}</style>
      <PrintControls orderId={null} kind="poster" preview={sp.preview === "1"} />
      <main className="poster">
        {ctx.restaurant.logo_url ? (
          // eslint-disable-next-line @next/next/no-img-element -- print page: plain img prints reliably
          <img className="logo" src={ctx.restaurant.logo_url} alt="" />
        ) : null}
        <h1>{ctx.restaurant.name}</h1>
        <div className="cta">{menu ? "Scan to see the menu & order" : "Scan to order on WhatsApp"}</div>
        <p className="urdu">{menu ? "Menu dekhne aur order karne ke liye scan karein" : "WhatsApp par order karne ke liye scan karein"}</p>
        <div className="qr" role="img" aria-label={menu ? "QR code to open the menu" : "QR code to open WhatsApp chat"} dangerouslySetInnerHTML={{ __html: svg }} />
        <p className="number">{account.display_phone_number}</p>
        <p className="help">Open your phone camera and point it at the code · Camera khol kar code par rakhein</p>
      </main>
    </>
  );
}

export default function WhatsAppPosterPage({ searchParams }: { searchParams: Promise<Search> }) {
  return (
    <Suspense fallback={null}>
      <Poster searchParams={searchParams} />
    </Suspense>
  );
}
